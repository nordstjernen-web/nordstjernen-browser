#!/usr/bin/env python3
"""gen-temporal-calendar-data.py — packs ICU4X's Chinese, Korean and Umm al-Qura year tables into quickjs-temporal-caldata.h."""
import datetime
import re
import sys
import urllib.request
from pathlib import Path

ICU4X_COMMIT = "bb3e1f9a0c966f7334aa400066f520f64f3dc3d6"
BASE = f"https://raw.githubusercontent.com/unicode-org/icu4x/{ICU4X_COMMIT}/components/calendar/src/cal/"
SOURCES = {
    "qing": "east_asian_traditional/qing_data.rs",
    "china": "east_asian_traditional/china_data.rs",
    "korea": "east_asian_traditional/korea_data.rs",
    "ummalqura": "hijri/ummalqura_data.rs",
}
OUT = Path(__file__).resolve().parent.parent / "src" / "quickjs" / "quickjs-temporal-caldata.h"
UNIX_EPOCH = datetime.date(1970, 1, 1)
ISLAMIC_CIVIL_EPOCH = datetime.date(622, 7, 19)


def fetch(name):
    local = Path(sys.argv[1]) / SOURCES[name] if len(sys.argv) > 1 else None
    if local and local.exists():
        return local.read_text(encoding="utf-8")
    with urllib.request.urlopen(BASE + SOURCES[name]) as r:
        return r.read().decode("utf-8")


def east_asian(text):
    rows = []
    pattern = re.compile(
        r"new\((\d+), \[([ls, ]+)\], (None|Some\((\d+)\)), gregorian\((\d+), (\d+), (\d+)\)\)")
    for m in pattern.finditer(text):
        year = int(m.group(1))
        lengths = [x.strip() == "l" for x in m.group(2).split(",")]
        leap = int(m.group(4)) if m.group(4) else 0
        start = datetime.date(int(m.group(5)), int(m.group(6)), int(m.group(7)))
        rows.append((year, lengths, leap, start))
    return rows


def civil_start(year):
    days = (year - 1) * 354 + (3 + 11 * year) // 30
    return (ISLAMIC_CIVIL_EPOCH - UNIX_EPOCH).days + days


def hijri(text):
    rows = []
    pattern = re.compile(r"try_new\((\d+), \[([ls, ]+)\], gregorian\((\d+), (\d+), (\d+)\)\)")
    for m in pattern.finditer(text):
        year = int(m.group(1))
        lengths = [x.strip() == "l" for x in m.group(2).split(",")]
        start = (datetime.date(int(m.group(3)), int(m.group(4)), int(m.group(5))) - UNIX_EPOCH).days
        rows.append((year, lengths, start))
    return rows


def pack_east_asian(rows):
    words = []
    for year, lengths, leap, start in rows:
        bits = sum(1 << i for i, long in enumerate(lengths) if long)
        doy = (start - datetime.date(year, 1, 1)).days
        assert 0 <= doy < 64 and leap < 16
        words.append(bits | (leap << 13) | (doy << 17))
    return words


def pack_hijri(rows):
    words = []
    for year, lengths, start in rows:
        bits = sum(1 << i for i, long in enumerate(lengths) if long)
        delta = start - civil_start(year)
        assert -8 <= delta < 8
        words.append(bits | ((delta + 8) << 12))
    return words


def emit(name, first, words):
    lines = [f"#define TP_{name.upper()}_FIRST_YEAR {first}",
             f"static const uint32_t tp_{name}_years[{len(words)}] = {{"]
    for i in range(0, len(words), 6):
        lines.append("    " + " ".join(f"0x{w:08x}," for w in words[i:i + 6]))
    lines.append("};")
    return lines


def main():
    qing = east_asian(fetch("qing"))
    china = qing + east_asian(fetch("china"))
    korea = qing + east_asian(fetch("korea"))
    for rows in (china, korea):
        years = [r[0] for r in rows]
        assert years == list(range(years[0], years[0] + len(years)))
    umm = hijri(fetch("ummalqura"))
    assert [r[0] for r in umm] == list(range(1300, 1300 + len(umm)))
    lines = [
        "/* quickjs-temporal-caldata.h — Chinese, Korean and Umm al-Qura year tables "
        f"(generated by scripts/gen-temporal-calendar-data.py from ICU4X {ICU4X_COMMIT[:12]}). */",
    ]
    lines += emit("china", china[0][0], pack_east_asian(china))
    lines += emit("korea", korea[0][0], pack_east_asian(korea))
    lines += emit("ummalqura", umm[0][0], pack_hijri(umm))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: china {len(china)}, korea {len(korea)}, ummalqura {len(umm)} years")


if __name__ == "__main__":
    main()
