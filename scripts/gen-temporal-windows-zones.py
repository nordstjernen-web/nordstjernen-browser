#!/usr/bin/env python3
"""gen-temporal-windows-zones.py — generates the Windows-to-IANA time zone table from CLDR windowsZones.xml."""
import re
import sys
import urllib.request
from pathlib import Path

CLDR_RELEASE = "release-48"
URL = ("https://raw.githubusercontent.com/unicode-org/cldr/"
       f"{CLDR_RELEASE}/common/supplemental/windowsZones.xml")
OUT = Path(__file__).resolve().parent.parent / "src" / "quickjs" / "quickjs-temporal-winzones.h"


def load():
    if len(sys.argv) > 1:
        return Path(sys.argv[1]).read_text(encoding="utf-8")
    with urllib.request.urlopen(URL) as r:
        return r.read().decode("utf-8")


def main():
    xml = load()
    pairs = re.findall(r'<mapZone other="([^"]+)" territory="001" type="([^"]+)"/>', xml)
    pairs.sort(key=lambda p: p[0].lower())
    lines = [
        "/* quickjs-temporal-winzones.h — Windows time zone names to IANA identifiers "
        f"(generated by scripts/gen-temporal-windows-zones.py from CLDR {CLDR_RELEASE}). */",
        "static const char *const tp_windows_zones[][2] = {",
    ]
    for windows, iana in pairs:
        lines.append(f'    {{ "{windows}", "{iana}" }},')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(pairs)} mappings to {OUT}")


if __name__ == "__main__":
    main()
