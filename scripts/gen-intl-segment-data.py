#!/usr/bin/env python3
# Generate src/quickjs/quickjs-intl-segment-data.h (UAX #29 break properties) from the Unicode Character Database.
import os
import re
import sys

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V",
       "T", "LV", "LVT"]
WB = ["Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Regional_Indicator", "Format", "Katakana", "Hebrew_Letter",
      "ALetter", "Single_Quote", "Double_Quote", "MidNumLet", "MidLetter", "MidNum", "Numeric", "ExtendNumLet",
      "WSegSpace"]
SB = ["Other", "CR", "LF", "Extend", "Sep", "Format", "Sp", "Lower", "Upper", "OLetter", "Numeric", "ATerm",
      "SContinue", "STerm", "Close"]
INCB = ["None", "Linker", "Consonant", "Extend"]
MAX = 0x110000


def ranges(path, field_filter=None):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [p.strip() for p in line.split(";")]
            if field_filter and not field_filter(parts):
                continue
            m = re.fullmatch(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?", parts[0])
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            yield lo, hi, parts


def fill(table, path, names, shift, field_filter=None, index=1):
    for lo, hi, parts in ranges(path, field_filter):
        v = names.index(parts[index])
        for c in range(lo, hi + 1):
            table[c] |= v << shift


def main():
    ucd, out_dir = sys.argv[1], sys.argv[2]
    table = [0] * MAX
    fill(table, os.path.join(ucd, "GraphemeBreakProperty.txt"), GCB, 0)
    fill(table, os.path.join(ucd, "WordBreakProperty.txt"), WB, 4)
    fill(table, os.path.join(ucd, "SentenceBreakProperty.txt"), SB, 9)
    fill(table, os.path.join(ucd, "DerivedCoreProperties.txt"), INCB, 13,
         lambda p: p[1] == "InCB", index=2)
    for lo, hi, parts in ranges(os.path.join(ucd, "emoji-data.txt"), lambda p: p[1] == "Extended_Pictographic"):
        for c in range(lo, hi + 1):
            table[c] |= 1 << 15
    for lo, hi, parts in ranges(os.path.join(ucd, "LineBreak.txt"), lambda p: p[1] == "SA"):
        for c in range(lo, hi + 1):
            table[c] |= 1 << 16
    for lo, hi, parts in ranges(os.path.join(ucd, "DerivedCoreProperties.txt"),
                                lambda p: len(p) == 2 and p[1] == "Alphabetic"):
        for c in range(lo, hi + 1):
            table[c] |= 1 << 17
    runs = []
    for c in range(MAX):
        if not runs or table[c] != table[runs[-1]]:
            runs.append(c)
    values = sorted({table[c] for c in runs})
    assert len(values) < 256
    index = {v: i for i, v in enumerate(values)}
    w = ["/* quickjs-intl-segment-data.h: UAX #29 break properties generated by scripts/gen-intl-segment-data.py. */",
         "",
         "static const uint32_t intl_segment_props[%d] = {" % len(values)]
    for i in range(0, len(values), 8):
        w.append("    " + " ".join("0x%05x," % v for v in values[i:i + 8]))
    w.append("};")
    w.append("static const uint32_t intl_segment_ranges[%d] = {" % len(runs))
    packed = ["0x%08x," % ((c << 8) | index[table[c]]) for c in runs]
    for i in range(0, len(packed), 8):
        w.append("    " + " ".join(packed[i:i + 8]))
    w.append("};")
    w.append("")
    path = os.path.join(out_dir, "quickjs-intl-segment-data.h")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(w))
    print("wrote %s (%d ranges, %d property sets)" % (path, len(runs), len(values)))


if __name__ == "__main__":
    main()
